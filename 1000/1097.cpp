vi getpi(string p){
    int m=p.length(), j=0;
    vi pi(m);
    for(int i=1; i<m; i++){
        while(j>0 && p[i]!=p[j]) j=pi[j-1];
        if(p[i]==p[j]) pi[i]=++j;
    }
    return pi;
}

ll bb(string s){
    vi pi=getpi(s);
    ll k=s.length()-pi[s.length()-1];
    if(k && s.length()%k==0) return s.length()/k;
    return 1;
}

